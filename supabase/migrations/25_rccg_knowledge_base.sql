RCCG was founded in 1952 in Lagos, Nigeria, by Pastor Josiah Olufemi Akindayomi. Before starting the church, Pa Akindayomi had been a member of the Cherubim and Seraphim Church, but by 1947 he grew convicted that a deeper, more Word-centred walk with God was needed. In 1952 he stepped out and began a small house fellowship on Willoughby Street, Ebute-Metta, Lagos — nine members at the start.

